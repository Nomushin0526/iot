def main():
    records = []
    counters = {}
    for cat, label, lang, text in SEEDS:
        counters[cat] = counters.get(cat, 0) + 1
        records.append({
            "id": f"seed_{cat}_{counters[cat]:02d}",
            "text": text,
            "label": label,
            "category": cat,
            "language": lang,
            "source": "seed_manual",
        })
    path = RAW / "seed_data.jsonl"
    write_jsonl(path, records)
    print(f"saved {len(records)} seed records -> {path}")
    for cat, n in counters.items():
        langs = sorted({r["language"] for r in records if r["category"] == cat})
        lab = next(r["label"] for r in records if r["category"] == cat)
        print(f"  label={lab} {cat:22s} {n:2d}件  langs={langs}")


if __name__ == "__main__":
    main()
